function build_PV_SingleDiode_Simulink_v0_1()
% build_PV_SingleDiode_Simulink_v0_1
%
% Builds and saves:
%   PV_SingleDiode_Model_v0_1.slx
%
% Requirements:
%   MATLAB + Simulink
%
% The generated model sweeps module voltage from 0 V to PVSDM.Vmax and
% evaluates the implicit single-diode equation in a MATLAB Function block.
% It outputs current and power, and stores V/I/P in the workspace.
%
% Run from a folder containing:
%   PV_SingleDiode_Params_v0_1.m

    clc;
    run('PV_SingleDiode_Params_v0_1.m');

    mdl = 'PV_SingleDiode_Model_v0_1';

    if bdIsLoaded(mdl)
        close_system(mdl,0);
    end
    if exist([mdl '.slx'],'file')
        delete([mdl '.slx']);
    end

    new_system(mdl);
    open_system(mdl);

    set_param(mdl, ...
        'StopTime','PVSDM.SweepTime', ...
        'Solver','ode23t', ...
        'MaxStep','0.01');

    % -----------------------------------------------------------------
    % Sources
    % -----------------------------------------------------------------
    add_block('simulink/Sources/Ramp',[mdl '/Voltage Sweep'], ...
        'Position',[40 90 120 120], ...
        'slope','PVSDM.Vmax/PVSDM.SweepTime', ...
        'start','0', ...
        'InitialOutput','0');

    add_block('simulink/Discontinuities/Saturation',[mdl '/Clamp V'], ...
        'Position',[160 88 220 122], ...
        'UpperLimit','PVSDM.Vmax', ...
        'LowerLimit','0');

    add_block('simulink/Sources/Constant',[mdl '/Irradiance multiplier'], ...
        'Position',[40 155 120 185], ...
        'Value','PVSDM.Gpu');

    names = {'Iph_ref','I0_ref','a_ref','Rs','Rsh'};
    vals  = {'PVSDM.Iph_ref','PVSDM.I0_ref','PVSDM.a_ref','PVSDM.Rs','PVSDM.Rsh'};
    y0 = 220;
    for k = 1:numel(names)
        add_block('simulink/Sources/Constant',[mdl '/' names{k}], ...
            'Position',[40 y0+45*(k-1) 120 y0+30+45*(k-1)], ...
            'Value',vals{k});
    end

    % -----------------------------------------------------------------
    % Single-diode implicit solver
    % -----------------------------------------------------------------
    add_block('simulink/User-Defined Functions/MATLAB Function', ...
        [mdl '/PV Single Diode'], ...
        'Position',[315 105 500 305]);

    rt = sfroot;
    chart = rt.find('-isa','Stateflow.EMChart','Path',[mdl '/PV Single Diode']);
    if isempty(chart)
        error('Could not access the MATLAB Function block.');
    end

    chart.Script = sprintf([ ...
        'function I = fcn(V,Gpu,Iph_ref,I0,a,Rs,Rsh)\n' ...
        '%%#codegen\n' ...
        '%% Implicit single-diode module equation solved by Newton iteration.\n' ...
        '%% Gpu is relative irradiance; 1.0 = calibration illumination.\n' ...
        'Iph = max(0, Iph_ref*Gpu);\n' ...
        'I = Iph;\n' ...
        'for k = 1:20\n' ...
        '    arg = (V + I*Rs)/max(a,1e-9);\n' ...
        '    arg = min(max(arg,-50),50);\n' ...
        '    ea = exp(arg);\n' ...
        '    F = I - Iph + I0*(ea - 1) + (V + I*Rs)/max(Rsh,1e-9);\n' ...
        '    dF = 1 + I0*ea*(Rs/max(a,1e-9)) + Rs/max(Rsh,1e-9);\n' ...
        '    step = F/max(dF,1e-12);\n' ...
        '    step = min(max(step,-0.5),0.5);\n' ...
        '    I = I - step;\n' ...
        'end\n' ...
        'end\n']);

    % -----------------------------------------------------------------
    % Power and outputs
    % -----------------------------------------------------------------
    add_block('simulink/Math Operations/Product',[mdl '/Power P=VI'], ...
        'Position',[555 185 600 225]);

    add_block('simulink/Sinks/Scope',[mdl '/I-V-P Scope'], ...
        'Position',[690 85 740 135], ...
        'NumInputPorts','3');

    add_block('simulink/Sinks/To Workspace',[mdl '/V to workspace'], ...
        'Position',[690 170 790 200], ...
        'VariableName','Vsim', ...
        'SaveFormat','Structure With Time');

    add_block('simulink/Sinks/To Workspace',[mdl '/I to workspace'], ...
        'Position',[690 220 790 250], ...
        'VariableName','Isim', ...
        'SaveFormat','Structure With Time');

    add_block('simulink/Sinks/To Workspace',[mdl '/P to workspace'], ...
        'Position',[690 270 790 300], ...
        'VariableName','Psim', ...
        'SaveFormat','Structure With Time');

    % -----------------------------------------------------------------
    % Wiring
    % MATLAB Function input order:
    % V, Gpu, Iph_ref, I0, a, Rs, Rsh
    % -----------------------------------------------------------------
    add_line(mdl,'Voltage Sweep/1','Clamp V/1','autorouting','on');
    add_line(mdl,'Clamp V/1','PV Single Diode/1','autorouting','on');
    add_line(mdl,'Irradiance multiplier/1','PV Single Diode/2','autorouting','on');
    add_line(mdl,'Iph_ref/1','PV Single Diode/3','autorouting','on');
    add_line(mdl,'I0_ref/1','PV Single Diode/4','autorouting','on');
    add_line(mdl,'a_ref/1','PV Single Diode/5','autorouting','on');
    add_line(mdl,'Rs/1','PV Single Diode/6','autorouting','on');
    add_line(mdl,'Rsh/1','PV Single Diode/7','autorouting','on');

    add_line(mdl,'Clamp V/1','Power P=VI/1','autorouting','on');
    add_line(mdl,'PV Single Diode/1','Power P=VI/2','autorouting','on');

    add_line(mdl,'Clamp V/1','I-V-P Scope/1','autorouting','on');
    add_line(mdl,'PV Single Diode/1','I-V-P Scope/2','autorouting','on');
    add_line(mdl,'Power P=VI/1','I-V-P Scope/3','autorouting','on');

    add_line(mdl,'Clamp V/1','V to workspace/1','autorouting','on');
    add_line(mdl,'PV Single Diode/1','I to workspace/1','autorouting','on');
    add_line(mdl,'Power P=VI/1','P to workspace/1','autorouting','on');

    % Model annotation
    Simulink.Annotation(mdl, sprintf([ ...
        'Single-Diode PV Module Model v0.1\\n' ...
        'Calibrated initially to 20260821_GSM_HLT_DC_R01\\n' ...
        'Purpose: steady-state I-V/P-V model validation before FRA interpretation.\\n' ...
        'Gpu=1 corresponds to the calibration illumination; absolute irradiance scaling is not yet validated.']));

    save_system(mdl,[mdl '.slx']);
    open_system(mdl);

    fprintf('\nCreated: %s.slx\n',mdl);
    fprintf('Run the model, then use Vsim, Isim and Psim from the workspace.\n');
    fprintf('For measured-vs-model validation, run compare_PV_SingleDiode_to_DC_v0_1.m\n\n');
end
